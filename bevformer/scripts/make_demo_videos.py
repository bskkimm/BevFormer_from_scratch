"""Render per-map demo videos of a trained checkpoint on validation scenes.

Each frame: the front camera with the *predicted* 3D boxes projected onto it (left)
and the BEV feature-distinctiveness map with ground-truth (green) and predicted
(orange) boxes (right). nuScenes keyframes are 2 Hz, so playing 240 consecutive
keyframes at 2 fps is exactly 2 minutes of real driving; several validation scenes
of the same map are chained to reach that length. Needs `ffmpeg` on PATH.

Writes one MP4 per map plus `manifest.json` and a static `index.html` into
`<run-dir>/videos`:

    python bevformer/scripts/make_demo_videos.py --run-dir runs/<name>
    python -m http.server 8765 --bind 127.0.0.1 --directory runs/<name>/videos
"""

from __future__ import annotations

import argparse
import collections
import html
import json
import pickle
import shutil
import subprocess
from pathlib import Path

import numpy as np
import torch
from matplotlib.backends.backend_agg import FigureCanvasAgg
from matplotlib.figure import Figure
from torch.utils.data import DataLoader, Subset

from bevformer.data.collate import collate_fn
from bevformer.data.nuscenes_dataset import BevFormerNuScenesDataset
from bevformer.engine.bev_vis import _draw_boxes, camera_rgb, distinctiveness, project_box_edges
from bevformer.engine.build import AMP_DTYPES, PC_RANGE, build_model, configure_runtime
from bevformer.engine.checkpoint import load_checkpoint
from bevformer.engine.evaluator import decode_predictions
from bevformer.engine.trainer import move_batch_to_device

FPS = 2  # nuScenes keyframe rate: playback is real time
DISTINCT_RANGE = (5.0, 22.0)  # fixed colour scale so brightness is comparable across frames
WIDTH, HEIGHT = 2000, 720
MIN_SCENE_FRAMES = 30  # nuScenes scenes have ~40 keyframes; skip truncated ones
FRAMES_PER_SCENE = 40


def scenes_by_map(dataset, dataroot: Path, version: str) -> dict[str, list[tuple[str, list[int]]]]:
    """{map name: [(scene label, dataset indices), ...]} for every scene in `dataset`."""
    meta = Path(dataroot).expanduser() / version
    scenes = {s["token"]: s for s in json.loads((meta / "scene.json").read_text())}
    logs = {entry["token"]: entry for entry in json.loads((meta / "log.json").read_text())}
    per_map: dict[str, collections.OrderedDict] = collections.defaultdict(collections.OrderedDict)
    for index, token in enumerate(dataset.sample_tokens):
        scene_token = dataset.samples[token]["scene_token"]
        per_map[logs[scenes[scene_token]["log_token"]]["location"]].setdefault(scene_token, []).append(index)
    return {
        location: [(scenes[token]["name"] + ": " + scenes[token]["description"], indices) for token, indices in d.items()]
        for location, d in per_map.items()
    }


def pick_scenes(scenes: list[tuple[str, list[int]]], frames: int) -> list[tuple[str, list[int]]]:
    """Evenly spread scenes of one map until `frames` keyframes are covered (varied time of day / weather)."""
    scenes = [s for s in scenes if len(s[1]) >= MIN_SCENE_FRAMES]
    count = -(-frames // FRAMES_PER_SCENE) + 1
    picks = list(dict.fromkeys(int(i * len(scenes) / count) for i in range(count)))
    total = 0
    result = []
    for pick in picks:
        if total >= frames:
            break
        result.append(scenes[pick])
        total += len(scenes[pick][1])
    return result


def load_validation_dataset(run_dir: Path, config: dict):
    """The val split with the run's image size and temporal queue.

    Uses the compact cache written by `watch_validation.py --prepare-cache` when it
    exists (it avoids loading the raw nuScenes tables); otherwise builds the dataset.
    """
    cache = run_dir / "validation-cache.pkl"
    if cache.exists():
        # Local cache generated by watch_validation.py --prepare-cache; never load an untrusted pickle.
        with cache.open("rb") as handle:
            return pickle.load(handle)["dataset"]
    return BevFormerNuScenesDataset(
        dataroot=config["dataroot"],
        version=config["version"],
        split="val",
        queue_length=config["queue_length"],
        image_size=(config["image_height"], config["image_width"]),
        pc_range=PC_RANGE,
        image_dtype="uint8",
    )


def render_frame(camera, pred_boxes, gt_boxes, lidar2img, features, header: str, footer: str) -> np.ndarray:
    """One RGB frame [HEIGHT, WIDTH, 3] uint8: camera + projected predictions | BEV distinctiveness."""
    fig = Figure(figsize=(WIDTH / 100, HEIGHT / 100), dpi=100, facecolor="black")
    canvas = FigureCanvasAgg(fig)
    grid = fig.add_gridspec(1, 2, width_ratios=[1280, 720], left=0, right=1, bottom=0, top=0.94, wspace=0.0)

    ax = fig.add_subplot(grid[0, 0])
    height, width = camera.shape[:2]
    ax.imshow(camera)
    for box in pred_boxes:
        for segment in project_box_edges(box, lidar2img):
            ax.plot(segment[:, 0], segment[:, 1], color="orange", linewidth=1.6)
    ax.set_xlim(0, width)
    ax.set_ylim(height, 0)
    ax.axis("off")

    ax = fig.add_subplot(grid[0, 1])
    extent = (PC_RANGE[0], PC_RANGE[3], PC_RANGE[1], PC_RANGE[4])
    ax.imshow(
        distinctiveness(features),
        origin="lower",
        extent=extent,
        cmap="magma",
        vmin=DISTINCT_RANGE[0],
        vmax=DISTINCT_RANGE[1],
        interpolation="nearest",
    )
    _draw_boxes(ax, gt_boxes, "lime")
    _draw_boxes(ax, pred_boxes, "orange")
    ax.plot(0, 0, marker="^", color="cyan", markersize=8)
    ax.set_xlim(extent[0], extent[1])
    ax.set_ylim(extent[2], extent[3])
    ax.axis("off")

    fig.text(0.01, 0.97, header, color="white", fontsize=14, va="center")
    fig.text(0.99, 0.97, footer, color="white", fontsize=14, va="center", ha="right")
    fig.text(0.01, 0.015, "Front camera: predicted boxes (orange)", color="white", fontsize=12)
    fig.text(
        0.99,
        0.015,
        "BEV feature distinctiveness: ground truth (green), predictions (orange)",
        color="white",
        fontsize=12,
        ha="right",
    )
    canvas.draw()
    return np.asarray(canvas.buffer_rgba())[..., :3].copy()


def open_encoder(path: Path) -> subprocess.Popen:
    """An ffmpeg process that turns raw RGB frames written to its stdin into an H.264 MP4."""
    command = [
        "ffmpeg", "-y", "-loglevel", "error",
        "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{WIDTH}x{HEIGHT}", "-r", str(FPS), "-i", "-",
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "20", "-preset", "medium",
        "-movflags", "+faststart", str(path),
    ]  # fmt: skip
    return subprocess.Popen(command, stdin=subprocess.PIPE)


def write_index(out_dir: Path, manifest: list[dict], title: str) -> Path:
    """A static page that lists the videos, so `python -m http.server` is all it takes to browse them."""
    sections = "\n".join(
        f"""<section>
  <h2>{html.escape(entry["map"])} <small>({entry["seconds"]:.0f} s)</small></h2>
  <video src="{html.escape(entry["file"])}" controls preload="metadata" loop muted></video>
  <small>{" &nbsp;&bull;&nbsp; ".join(html.escape(scene) for scene in entry["scenes"])}</small>
</section>"""
        for entry in manifest
    )
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title>
<style>
 body{{margin:0;background:#111;color:#eee;font:15px/1.5 system-ui,sans-serif}}
 main{{max-width:1500px;margin:0 auto;padding:16px}}
 h1{{font-size:22px;margin:8px 0}} h2{{font-size:17px;margin:0 0 4px}}
 p.note{{color:#aaa;margin:4px 0 16px}} section{{margin:0 0 28px}}
 video{{width:100%;background:#000;border-radius:6px}} small{{color:#999}}
</style></head><body><main>
<h1>{html.escape(title)}</h1>
<p class="note">Left: front camera with <b style="color:orange">predicted</b> 3D boxes. Right: BEV feature
distinctiveness with <b style="color:#7f7">ground truth</b> and <b style="color:orange">predicted</b> boxes.
Real-time playback at {FPS} frames/s (nuScenes keyframes): each video chains several validation scenes of one map.</p>
{sections}
</main></body></html>
"""
    path = out_dir / "index.html"
    path.write_text(page, encoding="utf-8")
    return path


@torch.no_grad()
def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run-dir", type=Path, required=True)
    parser.add_argument("--checkpoint", default="final.pth", help="file inside --run-dir, e.g. checkpoints/epoch_14.pth")
    parser.add_argument("--out-dir", type=Path, default=None, help="default: <run-dir>/videos")
    parser.add_argument("--seconds", type=int, default=120, help="length of each map's video")
    parser.add_argument("--score-threshold", type=float, default=0.3)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--maps", nargs="*", default=None, help="subset of map names (default: all)")
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    args = parser.parse_args()
    if shutil.which("ffmpeg") is None:
        raise SystemExit("ffmpeg is required to encode the videos (for example: sudo apt install ffmpeg)")

    config = json.loads((args.run_dir / "config.json").read_text())
    model_args = argparse.Namespace(**config)
    model_args.pretrained_backbone = False  # the weights come from the checkpoint
    configure_runtime(model_args)
    device = torch.device(args.device)
    amp_dtype = AMP_DTYPES[model_args.amp] if device.type == "cuda" else None

    dataset = load_validation_dataset(args.run_dir, config)
    plan = scenes_by_map(dataset, Path(config["dataroot"]), config["version"])

    model = build_model(model_args).to(device)
    state = load_checkpoint(args.run_dir / args.checkpoint, model, map_location=device)
    model.eval()

    out_dir = args.out_dir or args.run_dir / "videos"
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = out_dir / "manifest.json"
    manifest = {entry["map"]: entry for entry in json.loads(manifest_path.read_text())} if manifest_path.exists() else {}

    frames = args.seconds * FPS
    for location in sorted(plan):
        if args.maps and location not in args.maps:
            continue
        indices, labels = [], []
        for label, scene_indices in pick_scenes(plan[location], frames):
            indices += scene_indices
            labels += [label] * len(scene_indices)
        indices, labels = indices[:frames], labels[:frames]
        loader = DataLoader(Subset(dataset, indices), batch_size=1, num_workers=args.workers, collate_fn=collate_fn)
        path = out_dir / f"{location}.mp4"
        encoder = open_encoder(path)
        try:
            for number, batch in enumerate(loader):
                moved = move_batch_to_device(batch, device)
                with torch.autocast(device_type=device.type, dtype=amp_dtype, enabled=amp_dtype is not None):
                    outputs = model(moved["imgs"], moved["img_metas"], moved["can_bus"])
                boxes, scores, _ = decode_predictions(outputs["cls_scores"][-1][0], outputs["bbox_preds"][-1][0])
                features = outputs["bev_embed"][0].detach().float()
                features = features.reshape(model.encoder.bev_h, model.encoder.bev_w, -1).cpu()
                frame = render_frame(
                    camera_rgb(batch["imgs"][0, -1, 0]),
                    boxes[scores >= args.score_threshold].cpu(),
                    moved["gt_boxes_3d"][0].cpu(),
                    np.asarray(batch["img_metas"][0][-1]["lidar2img"][0]),
                    features,
                    header=f"{location}   {labels[number].split(':')[0]}",
                    footer=f"t = {number / FPS:5.1f} s   score >= {args.score_threshold}",
                )
                encoder.stdin.write(frame.tobytes())
                if number % 40 == 0:
                    print(f"{location}: frame {number}/{len(indices)}", flush=True)
        finally:
            encoder.stdin.close()
            encoder.wait()
        manifest[location] = {
            "map": location,
            "file": path.name,
            "seconds": len(indices) / FPS,
            "scenes": list(dict.fromkeys(labels)),
        }
        print(f"wrote {path} ({len(indices) / FPS:.0f} s)", flush=True)

    entries = [manifest[name] for name in sorted(manifest)]
    manifest_path.write_text(json.dumps(entries, indent=2))
    title = f"BEVFormer demo videos (epoch {state['epoch']})" if "epoch" in state else "BEVFormer demo videos"
    write_index(out_dir, entries, title)


if __name__ == "__main__":
    main()
