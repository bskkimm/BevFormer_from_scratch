"""Evaluate each saved epoch in a short-lived GPU process while training continues.

Logs `val/subset_*` to the training run's MLflow run at the checkpoint's epoch.
Run from the repository root (see COMMAND_GUIDE.md):

    python bevformer/scripts/watch_validation.py --prepare-cache --run-dir runs/<name> --run-id <mlflow run id>
    python -u bevformer/scripts/watch_validation.py --run-dir runs/<name> --run-id <mlflow run id>
"""

from __future__ import annotations

import argparse
import fcntl
import hashlib
import json
import os
import pickle
import resource
import subprocess
import sys
import time
from pathlib import Path


def pending_checkpoints(directory: Path, completed: set[int]) -> list[Path]:
    paths = [p for p in directory.glob("epoch_*.pth") if p.stem[6:].isdigit()]
    # Newest first: get a current point on the graph before backfilling history.
    return sorted(
        (p for p in paths if int(p.stem[6:]) not in completed),
        key=lambda p: int(p.stem[6:]),
        reverse=True,
    )


def available_memory_gib(path: Path = Path("/proc/meminfo")) -> float:
    for line in path.read_text().splitlines():
        if line.startswith("MemAvailable:"):
            return int(line.split()[1]) / (1024 * 1024)
    raise RuntimeError("Cannot read available system RAM")


def cache_settings(args, config):
    from bevformer.data import nuscenes_dataset

    keys = ("dataroot", "version", "queue_length", "image_height", "image_width")
    return {
        **{key: config[key] for key in keys},
        "samples": args.samples,
        "seed": args.seed,
        "dataset_source": hashlib.sha256(
            Path(nuscenes_dataset.__file__).read_bytes()
        ).hexdigest(),
    }


def prepare_cache(args, config):
    """Build while training is stopped; later evaluations only load compact arrays."""
    from bevformer.data.nuscenes_dataset import BevFormerNuScenesDataset
    from bevformer.engine.build import PC_RANGE
    from bevformer.engine.validation import select_indices

    dataset = BevFormerNuScenesDataset(
        dataroot=config["dataroot"],
        version=config["version"],
        split="val",
        queue_length=config["queue_length"],
        image_size=(config["image_height"], config["image_width"]),
        pc_range=PC_RANGE,
        image_dtype="uint8",
    )
    if not hasattr(dataset, "_boxes"):
        raise RuntimeError("Validation cache requires the compact-array dataset")
    indices = select_indices(dataset, args.samples, args.seed)
    cache = {
        "settings": cache_settings(args, config),
        "dataset": dataset,
        "indices": indices,
    }
    path = args.run_dir / "validation-cache.pkl"
    temporary = path.with_suffix(".tmp")
    with temporary.open("wb") as handle:
        pickle.dump(cache, handle, protocol=pickle.HIGHEST_PROTOCOL)
    os.replace(temporary, path)
    print(f"Prepared {path}: {path.stat().st_size / 2**20:.1f} MiB", flush=True)


def load_cache(args, config):
    path = args.run_dir / "validation-cache.pkl"
    if not path.exists():
        raise RuntimeError("Run --prepare-cache before starting validation")
    # Local cache generated by --prepare-cache; never load an untrusted pickle.
    with path.open("rb") as handle:
        cache = pickle.load(handle)
    if cache["settings"] != cache_settings(args, config):
        raise ValueError("Validation cache settings changed; rebuild before training")
    return cache["dataset"], cache["indices"]


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", type=Path, required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--samples", type=int, default=128)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--poll-seconds", type=float, default=60)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--memory-fraction", type=float, default=0.25)
    parser.add_argument("--prepare-cache", action="store_true")
    parser.add_argument("--min-free-ram-gib", type=float, default=8.0)
    parser.add_argument("--checkpoint", type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if (
        args.samples <= 0
        or args.poll_seconds <= 0
        or args.min_free_ram_gib < 0
        or not 0 < args.memory_fraction <= 1
    ):
        parser.error(
            "samples/poll-seconds must be positive; memory-fraction must be in (0,1]"
        )
    return args


def evaluate_checkpoint(args, config, client):
    import torch
    from torch.utils.data import DataLoader, Subset

    from bevformer.data.collate import collate_fn
    from bevformer.engine.build import (
        AMP_DTYPES,
        PC_RANGE,
        build_model,
        configure_runtime,
    )
    from bevformer.engine.checkpoint import load_checkpoint
    from bevformer.engine.validation import evaluate_loss, log_result
    from bevformer.models.losses.bevformer_loss import BEVFormerLoss

    start = time.monotonic()
    torch.set_num_threads(2)
    device = torch.device(args.device)
    if device.type == "cuda":
        torch.cuda.set_device(device)
        torch.cuda.set_per_process_memory_fraction(args.memory_fraction, device)
    model_args = argparse.Namespace(**config)
    model_args.pretrained_backbone = False
    configure_runtime(model_args)
    model = build_model(model_args)
    state = load_checkpoint(args.checkpoint, model, map_location="cpu")
    if state.get("mlflow_run_id") != args.run_id:
        raise ValueError("Checkpoint belongs to a different MLflow run")
    epoch = int(state["epoch"])
    model.to(device)
    dataset, indices = load_cache(args, config)
    tokens = [dataset.sample_tokens[i] for i in indices]
    fingerprint = hashlib.sha256(json.dumps(tokens).encode()).hexdigest()
    previous = client.get_run(args.run_id).data.tags.get("validation.subset_sha256")
    if previous and previous != fingerprint:
        raise ValueError(
            "Validation subset changed; refusing to mix incomparable metrics"
        )
    client.set_tag(args.run_id, "validation.subset_sha256", fingerprint)
    loader = DataLoader(
        Subset(dataset, indices),
        batch_size=1,
        shuffle=False,
        num_workers=0,
        collate_fn=collate_fn,
        pin_memory=False,
    )
    print(
        f"Evaluating epoch {epoch}: {len(indices)} fixed validation samples", flush=True
    )
    metrics = evaluate_loss(
        model,
        BEVFormerLoss(num_classes=config["num_classes"], pc_range=PC_RANGE),
        loader,
        device,
        AMP_DTYPES[config["amp"]],
    )
    elapsed = time.monotonic() - start
    peak_gib = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 2**20
    print(f"Peak evaluator RSS: {peak_gib:.2f} GiB", flush=True)
    completed = {
        m.step for m in client.get_metric_history(args.run_id, "val/subset_loss")
    }
    if epoch not in completed:
        log_result(client, args.run_id, epoch, metrics, elapsed)
    print(
        f'Evaluated epoch {epoch}: val/subset_loss={metrics["loss"]:.6f}, '
        f"duration={elapsed:.1f}s",
        flush=True,
    )


def main():
    args = parse_args()
    os.chdir(Path(__file__).resolve().parents[2])
    from mlflow.tracking import MlflowClient

    config = json.loads((args.run_dir / "config.json").read_text())
    if args.prepare_cache:
        prepare_cache(args, config)
        return
    client = MlflowClient(tracking_uri=config["mlflow_tracking_uri"])
    if args.checkpoint:
        evaluate_checkpoint(args, config, client)
        return
    # One watcher per directory; children exit after each epoch to free GPU memory.
    with (args.run_dir / "validation.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        lock.write(str(os.getpid()))
        lock.flush()
        settings = json.dumps(
            {"samples": args.samples, "seed": args.seed, "split": "val"}, sort_keys=True
        )
        previous = client.get_run(args.run_id).data.tags.get("validation.settings")
        if previous and previous != settings:
            raise ValueError(
                "Validation settings changed; use a separate metric series"
            )
        client.set_tag(args.run_id, "validation.settings", settings)
        print(
            f"Watching {args.run_dir} for epoch checkpoints; run={args.run_id}",
            flush=True,
        )
        # Import torch only in children: keep the idle watcher lightweight.
        while True:
            completed = {
                m.step
                for m in client.get_metric_history(args.run_id, "val/subset_loss")
            }
            paths = pending_checkpoints(args.run_dir / "checkpoints", completed)
            if paths:
                available = available_memory_gib()
                if available < args.min_free_ram_gib:
                    print(f"Waiting for RAM: {available:.1f} GiB available", flush=True)
                    time.sleep(args.poll_seconds)
                    continue
                command = [
                    sys.executable,
                    "-u",
                    str(Path(__file__).resolve()),
                    *sys.argv[1:],
                    "--checkpoint",
                    str(paths[0]),
                ]
                result = subprocess.run(command, check=False)
                if result.returncode:
                    print(
                        f"Validation failed ({result.returncode}); retrying in 60s",
                        flush=True,
                    )
                    time.sleep(60)
                continue
            if client.get_run(args.run_id).info.status != "RUNNING":
                print("Training ended and all saved epochs are evaluated.", flush=True)
                break
            time.sleep(args.poll_seconds)


if __name__ == "__main__":
    main()
